// Stable API guard. Collects the declaration files reachable from each stable entry point, removes
// comments and blank lines, and compares the result with api/stable-api.txt. Run after `npm run build`.
//   node scripts/check-api.mjs           fails if the stable declarations changed
//   node scripts/check-api.mjs --update  rewrites the baseline after a reviewed change
// Stability classes and the compatibility policy are in docs/stability.md.
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const baselinePath = path.join(root, 'api', 'stable-api.txt');

export const STABLE_ENTRY_POINTS = [
  '.',
  './contracts',
  './registry',
  './executor',
  './composition',
  './diagnostics',
  './auth',
  './schema/zod',
  './http',
  './mcp',
  './cli',
];

/** Removes comments outside string and template literals. */
export function stripComments(text) {
  let out = '';
  let quote = null;
  for (let i = 0; i < text.length; i += 1) {
    const char = text[i];
    const next = text[i + 1];
    if (quote) {
      out += char;
      if (char === '\\') {
        out += next ?? '';
        i += 1;
      } else if (char === quote) {
        quote = null;
      }
      continue;
    }
    if (char === '"' || char === "'" || char === '`') {
      quote = char;
      out += char;
    } else if (char === '/' && next === '/') {
      while (i < text.length && text[i] !== '\n') i += 1;
      out += '\n';
    } else if (char === '/' && next === '*') {
      i += 2;
      while (i < text.length && !(text[i] === '*' && text[i + 1] === '/')) i += 1;
      i += 1;
    } else {
      out += char;
    }
  }
  return out;
}

function normalize(text) {
  return stripComments(text.replace(/\r\n/g, '\n'))
    .split('\n')
    .map((line) => line.trim())
    .filter((line) => line.length > 0)
    .join('\n');
}

const RELATIVE_IMPORT = /(?:from|import)\s*\(?\s*['"](\.{1,2}\/[^'"]+)['"]/g;

export async function renderStableApi() {
  const manifest = JSON.parse(await readFile(path.join(root, 'package.json'), 'utf8'));
  const pending = [];
  const sections = [];
  for (const entry of STABLE_ENTRY_POINTS) {
    const target = manifest.exports[entry]?.types;
    if (!target) throw new Error(`stable entry ${entry} has no types target in package.json`);
    sections.push(`${entry} -> ${target.replace(/^\.\//, '')}`);
    pending.push(path.join(root, target));
  }
  const seen = new Map();
  while (pending.length > 0) {
    const file = pending.pop();
    if (seen.has(file)) continue;
    let text;
    try {
      text = await readFile(file, 'utf8');
    } catch {
      throw new Error(`missing ${path.relative(root, file)}; run npm run build first`);
    }
    const body = normalize(text);
    seen.set(file, body);
    for (const match of body.matchAll(RELATIVE_IMPORT)) {
      pending.push(path.resolve(path.dirname(file), match[1].replace(/\.js$/, '.d.ts')));
    }
  }
  const files = [...seen.entries()]
    .map(([file, body]) => [path.relative(root, file).replace(/\\/g, '/'), body])
    .sort(([a], [b]) => a.localeCompare(b));
  return [
    '# Stable API baseline. Generated by scripts/check-api.mjs; do not edit by hand.',
    '',
    '## Entry points',
    ...sections,
    ...files.flatMap(([file, body]) => ['', `## ${file}`, body]),
    '',
  ].join('\n');
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const current = await renderStableApi();
  if (process.argv.includes('--update')) {
    await writeFile(baselinePath, current);
    console.log(`wrote ${path.relative(root, baselinePath)}`);
  } else {
    const baseline = (await readFile(baselinePath, 'utf8').catch(() => '')).replace(/\r\n/g, '\n');
    if (baseline === current) {
      console.log(`stable API unchanged (${STABLE_ENTRY_POINTS.length} entry points)`);
    } else {
      const before = baseline.split('\n');
      const after = current.split('\n');
      const index = after.findIndex((line, i) => line !== before[i]);
      const header = after
        .slice(0, index + 1)
        .reverse()
        .find((line) => line.startsWith('## '));
      console.error(
        'The stable API changed. Follow docs/stability.md, then run: node scripts/check-api.mjs --update',
      );
      console.error(`first difference in ${header ?? 'the header'} at line ${index + 1}:`);
      console.error(`- ${before[index] ?? '(end)'}\n+ ${after[index] ?? '(end)'}`);
      process.exitCode = 1;
    }
  }
}
